import ExcelJS from "exceljs";
import { PRODUCT } from "../brand.js";
/*
 * The salary disbursement file HR uploads to corporate (net) banking after the payroll is approved.
 * It only describes the payments: nothing here talks to a bank or moves money. An authorized person uploads it in the
 * bank's portal, where the bank's own approval applies, and HR then marks the payroll processed with the bank's reference.
 *
 * The layout is a generic bulk-payment CSV (one row per payment, a header row, amounts in rupees with two decimals).
 * Banks differ in their templates: if yours needs other columns or order, change BANK_COLUMNS below; the data is the same.
 * PAYROLL_DEBIT_ACCOUNT (optional) fills the company's debit account column.
 */
export const BANK_COLUMNS = [
  ["Payment Reference", (p) => p.reference],
  ["Beneficiary Name", (p) => p.holder],
  ["Beneficiary Account Number", (p) => p.account],
  ["IFSC", (p) => p.ifsc],
  ["Beneficiary Bank", (p) => p.bankName],
  ["Amount", (p) => p.amount.toFixed(2)],
  ["Payment Mode", (p) => p.mode],
  ["Salary Month", (p) => p.month],
  ["Narration", (p) => p.narration],
  ["Employee ID", (p) => p.empNo],
  ["Debit Account", (p) => p.debitAccount],
];

/** "SAL202611WOH042": salary, month, employee number (letters and digits only, at most 20 characters, as banks accept). */
export const paymentReference = (period, empNo, email) =>
  `SAL${period.replace("-", "")}${String(empNo || email.split("@")[0]).toUpperCase().replace(/[^A-Z0-9]/g, "")}`.slice(0, 20);

/** A CSV cell. A value that a spreadsheet would read as a formula gets a leading apostrophe. */
const cell = (v) => {
  let s = String(v ?? "");
  if (/^[=+\-@\t\r]/.test(s)) s = "'" + s;
  return /[",\r\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
};

/** Payments in paise-exact rupees. Rows: [{ empNo, email, holder, account, ifsc, bankName, net }]. Returns { csv, payments, total, count }. */
export function buildBankFile(period, monthText, rows) {
  const debitAccount = (process.env.PAYROLL_DEBIT_ACCOUNT || "").trim();
  const payments = rows.map((r) => ({
    reference: paymentReference(period, r.empNo, r.email), holder: r.holder.slice(0, 50), account: r.account, ifsc: r.ifsc, bankName: r.bankName,
    amount: Math.round(r.net * 100) / 100, mode: r.ifsc.slice(0, 4) === (process.env.PAYROLL_DEBIT_BANK_CODE || "").toUpperCase() ? "IFT" : "NEFT",
    month: monthText, narration: `Salary ${monthText}`.slice(0, 30), empNo: r.empNo || "", debitAccount,
  }));
  const refs = new Set();
  for (const p of payments) {
    if (refs.has(p.reference)) { const e = new Error(`Two payments would have the reference ${p.reference}. Give each employee a distinct employee number.`); e.status = 422; throw e; }
    refs.add(p.reference);
  }
  const lines = [BANK_COLUMNS.map(([h]) => h).join(","), ...payments.map((p) => BANK_COLUMNS.map(([, f]) => cell(f(p))).join(","))];
  const totalPaise = payments.reduce((n, p) => n + Math.round(p.amount * 100), 0);
  return { csv: lines.join("\r\n") + "\r\n", payments, total: totalPaise / 100, count: payments.length };
}

/**
 * The same payments as an Excel sheet, for people who check or upload from Excel: one row per payment, the amount a real number, the account number kept as text,
 * a total with a formula, and a line comparing it with the approved net payable. Built from the payments buildBankFile made, so both files always agree.
 * It holds full account numbers like the CSV: it is stored encrypted and only people with the bank permission can download it.
 */
export async function buildBankWorkbook(period, monthText, payments, total, approvedNet, meta) {
  const wb = new ExcelJS.Workbook();
  wb.creator = PRODUCT; wb.created = new Date(meta.generatedAt); wb.calcProperties.fullCalcOnLoad = true;
  const ws = wb.addWorksheet("Salary transfer", { views: [{ state: "frozen", ySplit: 4 }], pageSetup: { orientation: "landscape", fitToPage: true, fitToWidth: 1, fitToHeight: 0, paperSize: 9 } });
  const heads = BANK_COLUMNS.map(([h]) => h), AMOUNT = heads.indexOf("Amount") + 1, ACCOUNT = heads.indexOf("Beneficiary Account Number") + 1;
  ws.mergeCells(1, 1, 1, heads.length); ws.mergeCells(2, 1, 2, heads.length);
  Object.assign(ws.getCell(1, 1), { value: `Salary transfer sheet · ${monthText}`, font: { bold: true, size: 14, color: { argb: "FF1B1650" } } });
  Object.assign(ws.getCell(2, 1), { value: `Version ${meta.version} · generated by ${meta.generatedBy}. This sheet only describes the payments; nothing here moves any money. Upload it in corporate banking, where the bank's own approval applies.`, font: { size: 10, color: { argb: "FF6B6B7B" } } });
  const thin = { style: "thin", color: { argb: "FFD5D5DE" } }, border = { top: thin, bottom: thin, left: thin, right: thin };
  ws.getRow(4).values = heads;
  ws.getRow(4).eachCell((c) => { c.font = { bold: true, color: { argb: "FFFFFFFF" } }; c.fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FF2F2A8C" } }; c.border = border; c.alignment = { vertical: "middle", wrapText: true }; });
  ws.getRow(4).height = 30;
  const widths = [20, 28, 24, 14, 24, 16, 12, 14, 18, 14, 20];
  heads.forEach((_, i) => { ws.getColumn(i + 1).width = widths[i] || 16; });
  payments.forEach((p, n) => {
    const row = ws.getRow(5 + n);
    row.values = BANK_COLUMNS.map(([h, f], i) => (i + 1 === AMOUNT ? Number(p.amount) : String(f(p) ?? "")));
    row.eachCell({ includeEmpty: true }, (c) => { c.border = border; });
    row.getCell(ACCOUNT).numFmt = "@";
    row.getCell(AMOUNT).numFmt = '"₹"#,##0.00';
  });
  const last = 4 + payments.length, totalRow = last + 1;
  const col = (n) => String.fromCharCode(64 + n);
  ws.getCell(totalRow, 1).value = `Total · ${payments.length} payment${payments.length === 1 ? "" : "s"}`;
  ws.getCell(totalRow, AMOUNT).value = { formula: `SUM(${col(AMOUNT)}5:${col(AMOUNT)}${Math.max(5, last)})`, result: total };
  ws.getCell(totalRow, AMOUNT).numFmt = '"₹"#,##0.00';
  ws.getRow(totalRow).eachCell({ includeEmpty: true }, (c) => { c.font = { bold: true }; c.fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FFEDEBFA" } }; c.border = border; });
  ws.getCell(totalRow + 2, 1).value = "Approved net payable"; ws.getCell(totalRow + 2, 1).font = { bold: true };
  ws.getCell(totalRow + 2, AMOUNT).value = approvedNet; ws.getCell(totalRow + 2, AMOUNT).numFmt = '"₹"#,##0.00';
  ws.getCell(totalRow + 3, 1).value = "Matches the total above?"; ws.getCell(totalRow + 3, 1).font = { bold: true };
  ws.getCell(totalRow + 3, AMOUNT).value = { formula: `IF(ROUND(${col(AMOUNT)}${totalRow}-${col(AMOUNT)}${totalRow + 2},2)=0,"Matches","Check")`, result: "Matches" };
  ws.autoFilter = { from: { row: 4, column: 1 }, to: { row: Math.max(4, last), column: heads.length } };
  return Buffer.from(await wb.xlsx.writeBuffer());
}
