/*
 * Writes the installable-app files into public/ from the brand file, so names and colours stay in one place
 * (brand.config.json): the web app manifest and the page shown when the phone is offline. Runs before every build
 * (npm run build) and can be run alone: node scripts/make-app-files.mjs. The service worker (public/sw.js) is hand-written.
 */
import fs from "node:fs";
const B = JSON.parse(fs.readFileSync(new URL("../brand.config.json", import.meta.url), "utf8"));
const C = B.colors, out = (f) => new URL(`../public/${f}`, import.meta.url);

const manifest = {
  name: B.product.name, short_name: B.product.name, description: B.product.lede,
  id: "/app/", start_url: "/app/dashboard", scope: "/", display: "standalone", orientation: "any",
  background_color: C.ivory, theme_color: C.maroon, lang: "en-IN", categories: ["business", "productivity"],
  icons: [
    { src: "/app-icon-192.png", sizes: "192x192", type: "image/png", purpose: "any" },
    { src: "/app-icon-512.png", sizes: "512x512", type: "image/png", purpose: "any" },
    { src: "/app-icon-maskable-512.png", sizes: "512x512", type: "image/png", purpose: "maskable" },
  ],
  shortcuts: [
    { name: "Apply for leave", url: "/app/leave/apply", icons: [{ src: "/app-icon-192.png", sizes: "192x192" }] },
    { name: "My attendance", url: "/app/my-attendance", icons: [{ src: "/app-icon-192.png", sizes: "192x192" }] },
    { name: "My pay", url: "/app/payslips", icons: [{ src: "/app-icon-192.png", sizes: "192x192" }] },
  ],
};
fs.writeFileSync(out("manifest.webmanifest"), `${JSON.stringify(manifest, null, 2)}\n`);

const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]);
fs.writeFileSync(out("offline.html"), `<!doctype html>
<!-- Generated by scripts/make-app-files.mjs from brand.config.json. Shown by the app when the phone has no connection. -->
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>You are offline | ${esc(B.product.name)}</title><meta name="theme-color" content="${C.maroon}"><link rel="icon" href="/favicon.svg">
<style>
:root{color-scheme:light dark}
body{margin:0;min-height:100vh;display:grid;place-items:center;background:${C.ivory};color:${C.ink};font:16px/1.6 Lato,system-ui,sans-serif;padding:24px;box-sizing:border-box}
main{max-width:28rem;text-align:center}
img{width:72px;height:72px}
h1{font:500 clamp(26px,6vw,34px)/1.2 Fraunces,Georgia,serif;color:${C.maroon};margin:16px 0 8px}
p{margin:0 0 24px;color:${C.muted}}
button{font:600 16px Fraunces,Georgia,serif;color:${C.ivory};background:linear-gradient(135deg,${C.terracotta},${C.maroon},${C.maroonDeep});border:0;border-radius:999px;min-height:48px;padding:0 28px;cursor:pointer}
button:focus-visible{outline:2px solid ${C.orange};outline-offset:3px}
@media (prefers-color-scheme:dark){body{background:#1b1214;color:${C.ivory}}h1{color:${C.ivory}}p{color:${C.beige}}}
</style></head>
<body><main><img src="/wohlig-smile-mark.svg" alt=""><h1>You are offline</h1>
<p>${esc(B.product.name)} needs a connection. Please check your internet, then try again.</p>
<button type="button" onclick="location.reload()">Try again</button></main></body></html>
`);
console.log("App files written: manifest.webmanifest, offline.html");
